'use strict';
/*
 * Build src/stages-cracked.js from the curated cracked-ice boards.
 *
 *   node tools/hazard-curate.js      # tools/hazard-shortlist.json -> tools/hazard-campaign.json
 *   node tools/cracked-campaign.js   # tools/hazard-campaign.json  -> src/stages-cracked.js
 *
 * The file extends TiltStages in place (stages 101-160, chapters 11-16), so
 * src/stages.js stays exactly what tools/floe-campaign.js generates and the game
 * needs no code of its own to see the extra band. Boards are already ordered by
 * the engine-proved shortest solution; chapters are ten boards each.
 */
var fs = require('fs');
var path = require('path');
var base = require('../src/stages.js');

var ROOT = path.resolve(__dirname, '..');
var curated = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools', 'hazard-campaign.json'), 'utf8')).stages;
var FIRST_ID = base.STAGES[base.STAGES.length - 1].id + 1;
var FIRST_CHAPTER = base.CHAPTERS[base.CHAPTERS.length - 1].number + 1;

// Ten names per chapter, none of them already a stage name.
var NAMES = [
  ['GLAZE', 'VERGLAS', 'SLUSH', 'BRASH', 'FLURRY', 'CIRRUS', 'SHEEN', 'HOARFROST', 'ICICLE', 'DRIZZLE'],
  ['SEAM', 'HALO', 'SPLINTER', 'SWELL', 'WEDGE', 'GAP', 'SPLIT', 'LEAD', 'POLYNYA', 'CHIP'],
  ['RIFT', 'FRACTURE', 'CLEAVE', 'TREMOR', 'OXBOW', 'KETTLE', 'ESKER', 'FIRN', 'NEVE', 'TALUS'],
  ['RUPTURE', 'DRUMLIN', 'QUAKE', 'GROWLER', 'BERGY', 'FELL', 'SKERRY', 'ARETE', 'SASTRUGI', 'COL'],
  ['TARN', 'FJELD', 'PINGO', 'SCREE', 'DEW', 'LULL', 'FOG', 'ECHO', 'VIGIL', 'SNOWFALL'],
  ['NADIR', 'UMBRA', 'WANE', 'DUSK', 'LEEWARD', 'FACET', 'WINDWARD', 'CRYSTAL', 'GLACIER', 'PERIGEE']
];
var CHAPTER_DEF = [
  { name: 'THIN ICE', ja: 'うす氷', note: 'Cracked ice: sliding across it is safe, stopping on it is not.' },
  { name: 'HAIRLINE', ja: 'ひび', note: 'Longer routes, with cracks in the way.' },
  { name: 'FAULT LINE', ja: '断層', note: 'Floes of every size, from 4×4 to 6×6.' },
  { name: 'SHATTER', ja: '砕氷', note: 'Routes past twenty-five moves.' },
  { name: 'CALVING', ja: '氷河の割れ目', note: 'Routes past thirty moves.' },
  { name: 'ABYSS', ja: '深淵', note: 'The longest cracked-ice routes found.' }
];
var HINTS = {
  away: { ja: '一度ゴールから遠ざかると、止まれる場所が見えてきます。', en: 'Moving away from a goal can reveal a place to stop.' },
  brake: { ja: '相棒に当たって止まる場所を探してみよう。', en: 'Look for a place where one penguin stops against the other.' },
  cross: { ja: '割れる氷は、すべって通り過ぎるだけなら大丈夫です。', en: 'Cracked ice is safe to slide across; it breaks only if you stop on it.' }
};
var INTRO = { ja: '割れる氷の上で止まると失敗。通り過ぎるだけなら大丈夫です。', en: 'Cracked ice breaks if you stop on it. Sliding across is safe.' };

var used = {};
base.STAGES.forEach(function (s) { used[s.name] = true; });
var stages = curated.map(function (c, i) {
  var chapter = Math.floor(i / 10), name = NAMES[chapter][i % 10];
  if (used[name]) throw new Error('stage name already taken: ' + name);
  used[name] = true;
  var order = [];
  if (c.notes.crossings) order.push('cross');
  if (c.notes.away) order.push('away');
  if (c.notes.brakes) order.push('brake');
  var hint = i % 10 === 0 ? INTRO : HINTS[order.length ? order[i % order.length] : 'cross'];
  return {
    id: FIRST_ID + i, name: name, par: c.par, idea: c.idea,
    hint: { ja: hint.ja, en: hint.en }, board: c.board
  };
});
var chapters = CHAPTER_DEF.map(function (def, k) {
  var from = FIRST_ID + k * 10, slice = stages.slice(k * 10, k * 10 + 10);
  var lo = slice[0].par, hi = slice[slice.length - 1].par;
  return {
    number: FIRST_CHAPTER + k, name: def.name, ja: def.ja, from: from, to: from + slice.length - 1,
    // Cracked ice is stacked on the two-penguin rules on purpose: qa.js and audit.js read this flag.
    extreme: true,
    note: def.note + ' Par ' + lo + '–' + hi + '.'
  };
});

var out = [];
out.push("'use strict';");
out.push('// Generated by tools/cracked-campaign.js from tools/hazard-campaign.json. Do not edit.');
out.push('// Extends TiltStages (loaded first) with the cracked-ice band: stages ' + stages[0].id + '-' + stages[stages.length - 1].id +
  ', chapters ' + chapters[0].number + '-' + chapters[chapters.length - 1].number + '.');
out.push('(function (root) {');
out.push('  var base = root.TiltStages;');
out.push("  if (!base) throw new Error('stages-cracked.js must be loaded after stages.js');");
out.push('  var CHAPTERS = ' + JSON.stringify(chapters, null, 2).replace(/\n/g, '\n  ') + ';');
out.push('  var STAGES = ' + JSON.stringify(stages, null, 2).replace(/\n/g, '\n  ') + ';');
out.push('  if (!base.STAGES.some(function (s) { return s.id === STAGES[0].id; })) {');
out.push('    base.STAGES.push.apply(base.STAGES, STAGES);');
out.push('    (base.CHAPTERS = base.CHAPTERS || []).push.apply(base.CHAPTERS, CHAPTERS);');
out.push('  }');
out.push('  root.TiltCrackedStages = { STAGES: STAGES, CHAPTERS: CHAPTERS };');
out.push("})(typeof globalThis !== 'undefined' ? globalThis : this);");
fs.writeFileSync(path.join(ROOT, 'src', 'stages-cracked.js'), out.join('\n') + '\n');
console.log(JSON.stringify({ stages: stages.length, ids: [stages[0].id, stages[stages.length - 1].id], chapters: chapters.map(function (c) { return c.number + ':' + c.name + ' ' + c.note.split('Par ')[1]; }) }));
